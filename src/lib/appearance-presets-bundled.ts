// src/lib/appearance-presets-bundled.ts
//
// The presets codeg ships. Each one is a complete document in the shareable
// format, so exporting a bundled preset and importing it back is the identity,
// and each is the reference for what a preset can express: palette, fonts,
// density, bubble and composer shape, code colours.
//
// Names and descriptions are neutral. Several looks are inspired by the
// palettes and typography of terminal-first agent UIs and editors, but every
// value here is our own and nothing is copied from another product.
//
// `appearance-presets-bundled.test.ts` validates every preset against the
// schema and checks every text / surface pair for WCAG AA contrast in both
// modes, so a palette edit that breaks readability fails the build.

